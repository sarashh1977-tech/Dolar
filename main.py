def api(method, _timeout=40, **params):
    try:
        r = requests.post(API + method, json=params, timeout=_timeout, proxies=PROXIES)
        return r.json()
    except Exception as e:
        return {"ok": False, "error_code": 0, "description": f"network: {e}"}


def send_text(chat_id, text, kb=None):
    p = {"chat_id": chat_id, "text": text, "disable_web_page_preview": True}
    if kb:
        p["reply_markup"] = kb
    return api("sendMessage", **p)


def show(chat_id, mid, text, kb=None):
    """پیام قبلی رو ویرایش می‌کنه (اگه نشد، پیام جدید می‌فرسته)."""
    if mid:
        p = {"chat_id": chat_id, "message_id": mid, "text": text, "disable_web_page_preview": True}
        if kb:
            p["reply_markup"] = kb
        r = api("editMessageText", **p)
        if r.get("ok") or "not modified" in (r.get("description") or ""):
            return r
