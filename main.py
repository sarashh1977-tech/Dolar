def _ocr_price_from_image(path_or_bytes):
    """استخراج عدد قیمت از تصویر استیکر با tesseract (چند روش)."""
    from PIL import Image, ImageOps, ImageEnhance
    import subprocess, tempfile

    if isinstance(path_or_bytes, (bytes, bytearray)):
        im0 = Image.open(io.BytesIO(path_or_bytes))
    else:
        im0 = Image.open(path_or_bytes)
    im0 = im0.convert("RGB")

    variants = []
    # نسخه اصلی بزرگ‌شده
    w, h = im0.size
    big = im0.resize((w * 2, h * 2), Image.LANCZOS)
    variants.append(big)
    # کنتراست بالا
    variants.append(ImageEnhance.Contrast(big).enhance(2.0))
    # سیاه‌وسفید
    variants.append(ImageOps.grayscale(big).convert("RGB"))
    # معکوس (متن سفید روی تیره)
    variants.append(ImageOps.invert(big))

    texts = []
    for im in variants:
        # pytesseract
        try:
            import pytesseract
            for psm in ("6", "11", "7", "4"):
                t = pytesseract.image_to_string(im, config=f"--psm {psm} -c tessedit_char_whitelist=0123456789,")
                if t and t.strip():
                    texts.append(t)
        except Exception:
            pass
        # CLI fallback
        try:
            png = tempfile.NamedTemporaryFile(suffix=".png", delete=False)
            im.save(png.name)
            png.close()
            for psm in ("6", "11", "7"):
                try:
                    out = subprocess.check_output(
                        ["tesseract", png.name, "stdout", "--psm", psm,
                         "-c", "tessedit_char_whitelist=0123456789,"],
                        stderr=subprocess.DEVNULL, timeout=15,
                    ).decode("utf-8", errors="ignore")
                    if out.strip():
                        texts.append(out)
                except Exception:
                    pass
            try:
                os.unlink(png.name)
            except Exception:
                pass
        except Exception:
            pass

    candidates = []
    for text in texts:
        for m in re.finditer(r"(\d{1,3}(?:[,\s.]\d{3})+|\d{5,7})", text):
            raw = m.group(1).replace(",", "").replace(" ", "").replace(".", "")
            try:
                v = int(raw)
                if 100000 <= v <= 900000:  # بازه منطقی دلار آزاد تومان
                    candidates.append(v)
            except Exception:
                pass
    if not candidates:
        # بدون whitelist هم یک‌بار
        try:
            import pytesseract
            t = pytesseract.image_to_string(big, config="--psm 6")
            for m in re.finditer(r"(\d{1,3}(?:,\d{3})+|\d{5,7})", t):
                v = int(m.group(1).replace(",", ""))
                if 100000 <= v <= 900000:
                    candidates.append(v)
        except Exception:
            pass
    if not candidates:
        return None
    # پرتکرارترین، وگرنه بزرگ‌ترین در بازه
    from collections import Counter
    c = Counter(candidates)
    return c.most_common(1)[0][0]


