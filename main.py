def exchange_usdt(ref=None):
    """(قیمت_میانه یا None ، جزئیات) — همه‌ی صرافی‌ها همزمان صدا زده میشن تا ربات منتظر نمونه."""
    from concurrent.futures import ThreadPoolExecutor
    details, values = [], []
    ex = ThreadPoolExecutor(max_workers=len(EXCHANGES))
    futs = [(name, ex.submit(fn)) for name, fn in EXCHANGES]
    for name, fut in futs:
        try:
            v = float(fut.result(timeout=12))
            if not (100_000 <= v <= 900_000):
                raise ValueError("عدد غیرعادی %s" % format(v, ",.0f"))
            if ref and abs(v - ref) / ref > 0.10:
                raise ValueError("با مرجع فاصله دارد (%s)" % format(v, ",.0f"))
            values.append(v)
            details.append((name, True, format(v, ",.0f")))
        except Exception as e:
            details.append((name, False, str(e)[:80] or type(e).__name__))
    ex.shutdown(wait=False)
    if not values:
        return None, details
    values.sort()
    n = len(values)
    mid = values[n // 2] if n % 2 else (values[n // 2 - 1] + values[n // 2]) / 2
    return int(round(mid)), details


