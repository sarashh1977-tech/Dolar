def _knorm(k):
    return re.sub(r"[^a-z0-9\u0600-\u06ff]", "", str(k).lower())


def _api_num(v):
    if isinstance(v, bool):
        return None
    if isinstance(v, (int, float)):
        return float(v)
    if isinstance(v, str):
        return _num(v.translate(_DIGITS))
    if isinstance(v, dict):
        for k in ("value", "price", "amount", "p"):
            for kk, vv in v.items():
                if _knorm(kk) == k:
                    return _api_num(vv)
    return None


def _find_usd(j, depth=0):
    if depth > 6:
        return None
    if isinstance(j, dict):
        for k, v in j.items():
            if _knorm(k) == "usd" and isinstance(v, (dict, int, float, str)):
                return v
        for k in ("symbol", "slug", "code", "key", "name", "id", "currency"):
            for kk, vv in j.items():
                if _knorm(kk) == k and isinstance(vv, str) and vv.strip().lower() == "usd":
                    return j
        for v in j.values():
            r = _find_usd(v, depth + 1)
            if r is not None:
                return r
    elif isinstance(j, list):
        for v in j:
            r = _find_usd(v, depth + 1)
            if r is not None:
                return r
    return None


def _api_age(node, root):
    for src in (node, root):
        if not isinstance(src, dict):
            continue
        for k, v in src.items():
            if _knorm(k) not in _TIME_KEYS:
                continue
            try:
                now = tehran_now().replace(tzinfo=None)
                if isinstance(v, (int, float)) and v > 1e9:
                    t = datetime.fromtimestamp(v / 1000 if v > 1e11 else v, timezone.utc) + timedelta(hours=3, minutes=30)
                    return (now - t.replace(tzinfo=None)).total_seconds() / 60
                if isinstance(v, str):
                    t = datetime.fromisoformat(v.strip().replace("Z", "+00:00"))
                    if t.tzinfo:
                        t = (t.astimezone(timezone.utc) + timedelta(hours=3, minutes=30)).replace(tzinfo=None)
                    return (now - t).total_seconds() / 60
            except Exception:
                continue
    return None


def parse_alanchand_api(j, sell_key=""):
    """از پاسخ JSON ی API: «قیمت فروش» دلار. ساختار پاسخ مستند نیست پس چند شکل رو می‌شناسه."""
    node = _find_usd(j)
    if node is None:
        raise ValueError("usd توی پاسخ نبود")
    sell = buy = None
    if isinstance(node, dict):
        items = {_knorm(k): v for k, v in node.items()}
        if sell_key and _knorm(sell_key) in items:
            sell = _api_num(items[_knorm(sell_key)])
        if sell is None:
            for k in _SELL_KEYS:
                if k in items and _api_num(items[k]):
                    sell = _api_num(items[k])
                    break
        if sell is None:
            for k, v in items.items():
                if ("sell" in k or "فروش" in k) and _api_num(v):
                    sell = _api_num(v)
                    break
        for k in _BUY_KEYS:
            if k in items and _api_num(items[k]):
                buy = _api_num(items[k])
                break
        if sell is None:     # فقط «price» داده شده (همون قیمت اصلی سایت = فروش)
            for k in _PRICE_KEYS:
                if k in items and _api_num(items[k]):
                    sell = _api_num(items[k])
                    break
    else:
        sell = _api_num(node)
    if sell is None:
        raise ValueError("فیلد قیمت فروش پیدا نشد")

    def fix(v):
        if v and v > 1_000_000:      # ریال → تومان
            v = v / 10
        return v
    sell, buy = fix(sell), fix(buy)
    if not (100_000 <= sell <= 900_000):
        raise ValueError("عدد غیرعادی: %s" % format(sell, ",.0f"))
    return {"sell": sell, "buy": buy, "age": _api_age(node, j)}


