    price = _r2(price)
    if last is None or price == _r2(last):
        key, dv = "flat", 0.0
    elif price > _r2(last):
        key, dv = "up", _r2(price - _r2(last))
    else:
        key, dv = "down", _r2(price - _r2(last))
