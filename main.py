def deliver(t, price, closed=False):
    res = send_sticker(t["chat_id"], price, t.get("last_price"), closed)
    if res.get("ok"):
        t["last_price"] = price
        t["last_sent"] = time.time()
        t["last_slot"] = slot_key(t["interval"])
        t["retry_at"] = 0
        t["warned"] = False
        save()
        return True

    desc = (res.get("description") or "")
    low = desc.lower()
    print("❌ ارسال ناموفق:", t["title"], desc)
    gone = any(x in low for x in ("kicked", "blocked", "chat not found", "deactivated", "not a member",
                                  "bot was blocked"))
    rights = any(x in low for x in ("not enough rights", "have no rights", "rights to send",
                                    "not allowed", "administrator rights"))
    owner = t.get("owner")
    if gone:
        S["targets"].pop(str(t["chat_id"]), None)
        save()
        if owner and owner != t["chat_id"]:
            send_text(owner, f"🚫 ربات از «{t['title']}» حذف شده یا بسته شده. این مقصد پاک شد.")
    elif (rights or res.get("error_code") == 403) and not t.get("warned"):
        t["warned"] = True
        t["last_sent"] = time.time()
        save()
        if owner:
            send_text(owner,
                      f"⚠️ دسترسی پیام دادن ربات در «{t['title']}» بسته است و نمی‌تونم قیمت بفرستم.\n\n"
                      "لطفاً دسترسی ارسال پیام/استیکر رو برای ربات فعال کن و بعد دکمه‌ی زیر رو بزن:",
                      {"inline_keyboard": [[btn("🔄 بررسی مجدد", f"recheck:{t['chat_id']}")]]})
    elif res.get("error_code") == 429:
        time.sleep(res.get("parameters", {}).get("retry_after", 3))
    t["retry_at"] = time.time() + 60      # تلاش مجدد بعد از یک دقیقه ، نه هر چند ثانیه
    return False


def slot_key(interval):
    """شناسه‌ی بازه‌ی زمانی فعلی (مثلا برای ۱۵ دقیقه: هر ربع ساعت یک اسلات)"""
    n = tehran_now()
    return "%s-%d" % (n.strftime("%Y%m%d"), (n.hour * 60 + n.minute) // max(1, int(interval)))


def run_schedule():
    now = time.time()
    due = []
    for t in list(S["targets"].values()):
        if not t.get("ready") or not window_ok(t):
            continue
        if t.get("retry_at", 0) > now:
            continue
        iv = int(t["interval"])
        if iv in (15, 30, 60):
            # دقیقا سر ربع/نیم/ساعت (طبق ساعت تهران) ارسال میشه
            if t.get("last_slot") == slot_key(iv):
                continue
        elif now - t.get("last_sent", 0) < iv * 60 - 30:
            continue
        if t.get("warned") and now - t.get("last_sent", 0) < 3600:
            continue  # مشکل دسترسی داره؛ ساعتی یک‌بار دوباره امتحان می‌کنیم
        due.append(t)
    if not due:
        return
    try:
        price, closed = cached_price()
    except Exception as e:
        print("price error:", e)
        for t in due:
            t["retry_at"] = now + 30
        return
    for t in due:
        deliver(t, price, closed)


