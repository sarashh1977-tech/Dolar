def check_post_rights(chat_id, kind):
    me = api("getChatMember", chat_id=chat_id, user_id=BOT_ID)
    if not me.get("ok"):
        return False, "ربات داخل این چت نیست. اول ربات رو اضافه کن."
    m = me["result"]
    st = m.get("status")
    if st in ("left", "kicked"):
        return False, "ربات داخل این چت نیست. اول ربات رو اضافه کن."
    if kind == "channel":
        if st != "administrator":
            return False, "ربات باید «ادمین» کانال باشه."
        if not m.get("can_post_messages"):
            return False, "توی تنظیمات ادمین ربات، گزینه‌ی «ارسال پیام» (Post Messages) رو فعال کن."
        return True, ""
    if st == "administrator":
        return True, ""
    msg = "اجازه‌ی ارسال پیام و استیکر برای ربات بسته است. ربات رو ادمین کن یا این اجازه رو بده."
    if st == "restricted":
        if not m.get("can_send_messages", True) or not m.get("can_send_other_messages", True):
            return False, msg
        return True, ""
    perms = api("getChat", chat_id=chat_id).get("result", {}).get("permissions")
    if perms and (not perms.get("can_send_messages", True) or not perms.get("can_send_other_messages", True)):
        return False, msg
    return True, ""


