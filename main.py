def register_chat(owner, chat_ref, notify_chat=None):
    """گروه/کانال رو بررسی می‌کنه و اگه همه‌چیز اوکی بود تنظیم زمان رو توی پیوی صاحبش شروع می‌کنه."""
    info = api("getChat", chat_id=chat_ref)
    if not info.get("ok"):
        send_text(owner, "❌ این گروه/کانال رو پیدا نکردم. مطمئن شو ربات داخلش اضافه شده.")
        return "error"
    chat = info["result"]
    cid, ctype = chat["id"], chat["type"]
    if ctype == "private":
        return "error"
    kind = "channel" if ctype == "channel" else "group"
    title = chat.get("title") or str(cid)

    adm = api("getChatMember", chat_id=cid, user_id=owner).get("result", {}).get("status")
    if adm not in ("creator", "administrator"):
        send_text(owner, f"⛔️ فقط ادمین «{title}» می‌تونه ربات رو تنظیم کنه.")
        return "denied"

    ok, why = check_post_rights(cid, kind)
    if not ok:
        r = send_text(owner,
                      f"⚠️ دسترسی پیام دادن ربات در «{title}» بسته است.\n\n{why}\n\n"
                      "بعد از فعال کردنش دکمه‌ی زیر رو بزن:",
                      {"inline_keyboard": [[btn("🔄 بررسی مجدد", f"recheck:{cid}")]]})
        if not r.get("ok") and notify_chat:
            send_text(notify_chat, f"⚠️ {why}\n\nو بعدش وارد پیوی ربات شو: https://t.me/{BOT_NAME}")
        return "no_rights"

    ensure_target(cid, owner, title, kind)
    FLOW[owner] = {"chat_id": cid}
    WAIT.pop(owner, None)
    r = step_start(owner, cid)
    if not r.get("ok"):
        if notify_chat:
            send_text(notify_chat,
                      "❗️ اول وارد پیوی ربات شو و Start بزن، بعد دوباره اینجا /start بفرست:\n"
                      f"https://t.me/{BOT_NAME}")
        return "dm_failed"
    return "ok"


